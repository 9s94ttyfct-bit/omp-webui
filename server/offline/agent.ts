/**
 * The agent directory of Light mode (`PI_CODING_AGENT_DIR` of a Light omp process), built from the user's own and never
 * written back to it. omp reads its models, MCP servers, settings and AGENTS.md from the agent directory, and nothing
 * it takes from there can be restricted per process any other way: the user's `~/.omp/agent` stays as it is for the
 * terminal and for Full mode. There are two kinds of directory: one for Light with a local server's models (`writeOfflineAgent`:
 * every model role is the server's), and one for Light with the user's own models (`writeYoursAgent`: their models.yml,
 * model roles and logins, with only what Light loads restricted).
 */

/** omp's chat model roles. The others (image, web, speech, dictation, judge) take models of other kinds. */
export const CHAT_ROLES = ["default", "smol", "slow", "vision", "plan", "commit", "tiny", "memory", "task", "advisor"];

/**
 * Plugin sources in omp's one `disabledProviders` namespace: plugins add MCP servers, hooks, commands and skills of their
 * own that neither the MCP checklist nor the skill filter would hold back, so a Light process has none.
 */
export const PLUGIN_PROVIDERS = ["omp-plugins", "claude-plugins", "agent-plugins"];

/**
 * Ids in omp's one `disabledProviders` namespace that a Light process on a local server must not use. The local engines
 * omp finds on its own: their models are not the chosen backend's (which is taken off the list in `offlineConfig`). And
 * the plugin sources.
 */
export const DISABLED_PROVIDERS = ["ollama", "lm-studio", "llama.cpp", "apple", ...PLUGIN_PROVIDERS];

const HEADER =
	"# Generated by omp-webui for Light mode. Not changed once written: another configuration gets a directory of its own.\n";

/** What Light mode reads from the user's agent directory. */
export interface UserFiles {
	modelsYaml: string | null;
	/** Every server in mcp.json, as the user wrote it. */
	mcpServers: Record<string, unknown>;
	agentsMd: string | null;
}

function readText(path: string): string | null {
	try {
		return readFileSync(path, "utf8");
	} catch {
		return null;
	}
}

/** The user's config.yml as written (read for Light with their own models only: it is the base of that process's settings). */
export function readUserConfig(agentDir: string): string | null {
	return readText(join(agentDir, "config.yml"));
}

export function readUserFiles(agentDir: string): UserFiles {
	let mcpServers: Record<string, unknown> = {};
	const mcp = readText(join(agentDir, "mcp.json"));
	if (mcp !== null) {
		try {
			const doc: unknown = JSON.parse(mcp);
			if (isRecord(doc) && isRecord(doc.mcpServers)) mcpServers = doc.mcpServers;
		} catch {
			// not JSON: omp reports that; there is nothing to offer here
		}
	}
	return {
		modelsYaml: readText(join(agentDir, "models.yml")),
		mcpServers,
		agentsMd: readText(join(agentDir, "AGENTS.md")),
	};
}

/**
 * What omp's own provider of a local engine is, which the user's models.yml entry (if it has one) is completed with:
 * omp finds an engine by itself only while models.yml has no provider of its name, and an entry with just a
 * `baseUrl` would leave it with no way to list models. oMLX has none: its entry is the user's, as written.
 * omp's discovery gives a loopback engine a quarter of a second, so that a service nobody started cannot stall its
 * startup; this engine was chosen, and has just answered the list of its models, so it is given a few seconds.
 */
const ENGINE_DEFAULTS: Partial<Record<Backend, Record<string, unknown>>> = {
	ollama: { api: "openai-responses", discovery: { type: "ollama", timeoutMs: 3000 } },
	"lm-studio": { api: "openai-completions", discovery: { type: "lm-studio", timeoutMs: 3000 } },
};

/** The host of `url`; null when it is not an address. */
function hostOf(url: string): string | null {
	try {
		return new URL(url).hostname;
	} catch {
		return null;
	}
}

/**
 * models.yml reduced to the provider of `backend`, and nothing else: the offline process has no other provider to
 * call, and whatever else the file holds (the keys of the user's other providers, in entries or in anchors that
 * hold them) has no business in a second file. The address is `baseUrl` (set in Settings), else the one in the
 * user's entry, else the backend's default. Ollama and LM Studio need no entry at all; oMLX does.
 *
 * The credentials of the entry (`apiKey`, `headers`) were written for the entry's own address. An address typed in
 * Settings that leads out of the user's network, and is not the entry's own host, is not sent them: after a slip of
 * the keyboard they would go, with every prompt, to a stranger.
 */
export function offlineModels(
	text: string | null,
	path: string,
	backend: Backend,
	baseUrl: string | null = null,
): { yaml: string; provider: BackendProvider; source: BaseUrlSource } {
	const missing = new OfflineError(
		`Light mode on a local server needs a provider named "${backend}" (with a baseUrl) in ${path}; none was found.`,
		"offlineProviderMissing",
		{ backend, path },
	);
	let doc: Record<string, unknown> = {};
	if (text !== null) {
		let parsed: unknown;
		try {
			parsed = Bun.YAML.parse(text);
		} catch (e) {
			const why = e instanceof Error ? e.message : String(e);
			throw new OfflineError(`${path} could not be read: ${why}`, "offlineModelsUnreadable", { path, reason: why });
		}
		if (isRecord(parsed)) doc = parsed;
	}
	const entry = isRecord(doc.providers) && isRecord(doc.providers[backend]) ? doc.providers[backend] : null;
	const own = typeof entry?.baseUrl === "string" && entry.baseUrl ? entry.baseUrl : null;
	const url = baseUrl ?? own ?? DEFAULT_BASE_URLS[backend];
	if (url === null || (backend === "omlx" && !entry)) throw missing;
	const merged: Record<string, unknown> = { ...ENGINE_DEFAULTS[backend], ...entry, baseUrl: url };
	const strangers = baseUrl !== null && classifyUrl(url) === "public" && !(own !== null && hostOf(own) === hostOf(url));
	const withheld = strangers && ("apiKey" in merged || "headers" in merged);
	const { apiKey: _key, headers: _headers, ...uncredentialed } = merged;
	const provider = strangers ? uncredentialed : merged;
	// The engines need no key; one the user wrote is theirs.
	if (backend !== "omlx" && provider.apiKey === undefined && provider.auth === undefined) provider.auth = "none";
	return {
		yaml: HEADER + Bun.YAML.stringify({ providers: { [backend]: provider } }, null, 2),
		provider: {
			baseUrl: url,
			apiKey: typeof provider.apiKey === "string" ? provider.apiKey : null,
			...(withheld ? { keyWithheld: true } : {}),
		},
		source: baseUrl ? "settings" : own ? "models.yml" : "default",
	};
}

/** mcp.json with the selected servers only, each as the user wrote it; `missing`: selected names it does not have. */
export function offlineMcp(
	servers: Record<string, unknown>,
	selected: readonly string[],
): { json: string; missing: string[] } {
	const present = selected.filter((name) => Object.hasOwn(servers, name));
	const chosen = Object.fromEntries(present.map((name) => [name, servers[name]]));
	return {
		json: `${JSON.stringify({ mcpServers: chosen }, null, 2)}\n`,
		missing: selected.filter((name) => !present.includes(name)),
	};
}

/** The offline process's own settings: every chat role is `model`, and only what was selected is loaded. */
export function offlineConfig(settings: OfflineSettings, model: string): string {
	return (
		HEADER +
		Bun.YAML.stringify(
			{
				modelRoles: Object.fromEntries(CHAT_ROLES.map((role) => [role, model])),
				defaultThinkingLevel: settings.thinking,
				// Restricts the models omp offers and starts with; the disabled providers cover the rest. `**`, not `*`:
				// a glob's `*` stops at a slash, and LM Studio's ids have them (`qwen/qwen3-8b`).
				enabledModels: [`${settings.backend}/**`],
				disabledProviders: DISABLED_PROVIDERS.filter((id) => id !== settings.backend),
				skills: settings.skills.length ? { includeSkills: settings.skills } : { enabled: false },
				// A project's own .mcp.json would add servers the checklist knows nothing about.
				mcp: { enableProjectConfig: false },
			},
			null,
			2,
		)
	);
}

export interface OfflineAgent {
	/** `<data dir>/offline-agent`: each configuration has a directory of its own in it, named by a digest of its content. */
	root: string;
	/** The user's agent directory (read from, never written). */
	agentDir: string;
	/** The user's sessions directory: Light conversations are saved there, so history lists them. */
	sessionsDir: string;
	settings: OfflineSettings;
	/** `<backend>/<id>`: the model of every role. */
	model: string;
	user: UserFiles;
	/** models.yml reduced to the backend's provider (see `offlineModels`). */
	modelsYaml: string;
}

/** What a Light directory shares with the user's agent directory: `[name, target, create]`; `create`: the target is made if it is not there. */
type Shared = [name: string, target: string, create: boolean][];

/**
 * Shared with the user's agent directory. A conversation is saved in the user's sessions directory (history lists
 * it, the terminal can resume it), and the images in it are blobs of the user's agent directory, which a Full
 * process must still find. Skills and prompt history are shared so that the skill filter and word prediction see
 * what they see in Full.
 */
function sharedWithUser(agentDir: string, sessionsDir: string): Shared {
	return [
		["sessions", sessionsDir, true],
		["blobs", join(agentDir, "blobs"), true],
		["skills", join(agentDir, "skills"), false],
		["history.db", join(agentDir, "history.db"), false],
	];
}

/**
 * Make the directory for `files` and the links to what exists of `shared`, if it does not exist yet; its name is a digest
 * of both. What exists to link to is part of the configuration: it is decided when the directory is made. A directory is
 * built aside and renamed into place whole, and never changed afterwards.
 */
function materialize(root: string, files: [name: string, content: string][], shared: Shared): string {
	const links: [name: string, target: string][] = [];
	for (const [name, target, create] of shared) {
		if (create) mkdirSync(target, { recursive: true });
		if (existsSync(target)) links.push([name, target]);
	}

	const revision = createHash("sha256")
		.update(JSON.stringify([files, links]))
		.digest("hex")
		.slice(0, 16);
	const dir = join(root, revision);
	if (existsSync(dir)) {
		// In use again: not one to collect (see `collectOfflineAgents`).
		const now = new Date();
		utimesSync(dir, now, now);
		return dir;
	}
	mkdirSync(root, { recursive: true, mode: 0o700 });
	const aside = mkdtempSync(join(root, `.${revision}-`));
	try {
		for (const [name, content] of files) writeFileSync(join(aside, name), content, { mode: 0o600 });
		for (const [name, target] of links) symlinkSync(target, join(aside, name));
		renameSync(aside, dir);
	} catch (e) {
		rmSync(aside, { recursive: true, force: true });
		// Made by someone else meanwhile: the same configuration, so the same directory.
		if (!existsSync(dir)) throw e;
	}
	return dir;
}

/**
 * The agent directory for Light with a local server's models, made if it does not exist yet. A directory is never changed
 * once it is there (it is built aside and renamed into place whole): an omp process started in it watches its `config.yml`
 * and rebuilds its models when that changes, so a conversation open on one backend would lose its provider the moment
 * another conversation started on a different one. The directory's name is a digest of what it holds, so the same
 * files and settings find the directory they had; edits to the user's models.yml, mcp.json or AGENTS.md apply to the
 * next process by getting one of their own. `missing`: the selected MCP servers the user's mcp.json no longer has.
 */
export function writeOfflineAgent(a: OfflineAgent): { dir: string; missing: string[] } {
	const mcp = offlineMcp(a.user.mcpServers, a.settings.mcp);
	const files: [name: string, content: string][] = [
		["models.yml", a.modelsYaml],
		["mcp.json", mcp.json],
		["config.yml", offlineConfig(a.settings, a.model)],
	];
	if (a.settings.agentsMd && a.user.agentsMd !== null) files.push(["AGENTS.md", a.user.agentsMd]);
	return { dir: materialize(a.root, files, sharedWithUser(a.agentDir, a.sessionsDir)), missing: mcp.missing };
}

/** The sources of omp's settings that Light with the user's own models builds the process's `config.yml` from. */
export interface YoursAgent {
	root: string;
	agentDir: string;
	sessionsDir: string;
	settings: OfflineSettings;
	user: UserFiles;
	/** The user's config.yml as written (`readUserConfig`); null: they have none. */
	configYaml: string | null;
}

/** A record of `doc` under `key`, or nothing. */
function section(doc: Record<string, unknown>, key: string): Record<string, unknown> {
	const v = doc[key];
	return isRecord(v) ? v : {};
}

/**
 * The user's own config.yml with what Light restricts put over it: the skills, MCP project config and plugin sources.
 * Everything else (their model roles and `enabledModels`, thinking level, retry and compaction settings) is as they have
 * it: Light with their own models changes which tools, MCP servers and skills load, not which models run. Throws when the
 * file cannot be read: running on defaults in its place would not be their models.
 */
export function yoursConfig(settings: OfflineSettings, text: string | null, path: string): string {
	let doc: Record<string, unknown> = {};
	if (text !== null) {
		let parsed: unknown;
		try {
			parsed = Bun.YAML.parse(text);
		} catch (e) {
			const why = e instanceof Error ? e.message : String(e);
			throw new OfflineError(`${path} could not be read: ${why}`, "offlineModelsUnreadable", { path, reason: why });
		}
		if (isRecord(parsed)) doc = parsed;
	}
	const kept = Array.isArray(doc.disabledProviders)
		? doc.disabledProviders.filter((id): id is string => typeof id === "string")
		: [];
	// What the user switched `enabled` for is not Light's to keep: Light's list says which skills load.
	const { enabled: _enabled, ...skills } = section(doc, "skills");
	return (
		HEADER +
		Bun.YAML.stringify(
			{
				...doc,
				disabledProviders: [...new Set([...kept, ...PLUGIN_PROVIDERS])],
				skills: settings.skills.length ? { ...skills, includeSkills: settings.skills } : { ...skills, enabled: false },
				// A project's own .mcp.json would add servers the checklist knows nothing about.
				mcp: { ...section(doc, "mcp"), enableProjectConfig: false },
			},
			null,
			2,
		)
	);
}

/** The files of the user's agent directory that hold their own models and logins, which Light with their own models links rather than copies. */
const OWN_MODEL_FILES = ["models.yml", "agent.db", "models.db"];

/**
 * The agent directory for Light with the user's own models, made if it does not exist yet (see `writeOfflineAgent`; it is
 * built and named the same way). Their models.yml and the databases that hold their logins and the models omp found are
 * linked, not copied: no second file holds their keys, and a login omp refreshes (OAuth tokens rotate) is refreshed for
 * every process. Their config.yml is copied with Light's restrictions put over it (`yoursConfig`), so a change to it
 * reaches the processes started after it, as the MCP servers and AGENTS.md do.
 */
export function writeYoursAgent(a: YoursAgent): { dir: string; missing: string[] } {
	const mcp = offlineMcp(a.user.mcpServers, a.settings.mcp);
	const files: [name: string, content: string][] = [
		["mcp.json", mcp.json],
		["config.yml", yoursConfig(a.settings, a.configYaml, join(a.agentDir, "config.yml"))],
	];
	if (a.settings.agentsMd && a.user.agentsMd !== null) files.push(["AGENTS.md", a.user.agentsMd]);
	const shared: Shared = [
		...sharedWithUser(a.agentDir, a.sessionsDir),
		...OWN_MODEL_FILES.map((name): Shared[number] => [name, join(a.agentDir, name), false]),
	];
	return { dir: materialize(a.root, files, shared), missing: mcp.missing };
}

/** A directory of `writeOfflineAgent`: its name is a digest. */
const REVISION_DIR = /^[0-9a-f]{16}$/;
/** A directory being built (`writeOfflineAgent`), or left half built by a server that ended meanwhile. */
const UNFINISHED_DIR = /^\.[0-9a-f]{16}-/;
/** What the one directory `offline-agent` held before each configuration had its own. */
const LEGACY_FILES = ["models.yml", "mcp.json", "config.yml", "AGENTS.md"];
const LEGACY_LINKS = ["sessions", "blobs", "skills", "history.db"];

/** How long a directory is left alone after its last use: a process being started is in no list yet. */
export const COLLECT_GRACE_MS = 10 * 60_000;

/**
 * Remove the agent directories under `root` that no process uses. `inUse`: the agent directories of the processes that
 * run (and of the paused ones, which outlive the server: they would find theirs gone when they are resumed). A
 * directory used within `graceMs` stays whatever the lists say. The legacy files of the single directory that
 * `root` once was (a models.yml among them, which kept the keys of every provider) go unless a process still uses `root` itself.
 * Returns the names removed.
 */
export function collectOfflineAgents(
	root: string,
	inUse: readonly string[],
	now = Date.now(),
	graceMs = COLLECT_GRACE_MS,
): string[] {
	let names: string[];
	try {
		names = readdirSync(root);
	} catch {
		return [];
	}
	const used = inUse.map((d) => resolve(d));
	const rootUsed = used.includes(resolve(root));
	const removed: string[] = [];
	for (const name of names) {
		const path = join(root, name);
		const stat = lstatSync(path, { throwIfNoEntry: false });
		if (!stat) continue;
		if (REVISION_DIR.test(name) || UNFINISHED_DIR.test(name)) {
			if (used.includes(resolve(path)) || now - stat.mtimeMs < graceMs) continue;
			rmSync(path, { recursive: true, force: true });
		} else if (!rootUsed && LEGACY_FILES.includes(name) && stat.isFile()) {
			rmSync(path, { force: true });
		} else if (!rootUsed && LEGACY_LINKS.includes(name) && stat.isSymbolicLink()) {
			// Only the link: what it points at is the user's.
			unlinkSync(path);
		} else continue;
		removed.push(name);
	}
	return removed;
}
