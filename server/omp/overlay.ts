import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { run } from "./run.ts";

/** `omp config get` for the overlay: the server does not listen before it, so it is given less than other reads. */
const STARTUP_MS = 10_000;

/**
 * A `--config` overlay applied to the omp processes the web UI starts. It only
 * adapts behaviour omp gates on the host type: the web UI is an interactive
 * host, so goal mode continues on its own as it does in the TUI. The user's
 * own settings are read first and extended, never replaced or written. The server
 * waits for it before it listens, so an omp that does not answer within `timeoutMs`
 * is taken for one without the setting (#319).
 */
export async function writeOverlay(bin: string, dataDir: string, timeoutMs = STARTUP_MS): Promise<string> {
	const modes = await currentContinuationModes(bin, timeoutMs);
	if (!modes.includes("rpc")) modes.push("rpc");
	const file = join(dataDir, "omp-overlay.yml");
	writeFileSync(
		file,
		`# Generated by omp-webui; passed to omp with --config.\ngoal:\n  continuationModes: ${JSON.stringify(modes)}\n`,
		{ mode: 0o600 },
	);
	return file;
}

async function currentContinuationModes(bin: string, timeoutMs: number): Promise<string[]> {
	try {
		const ran = await run([bin, "config", "get", "goal.continuationModes"], { timeoutMs });
		const parsed: unknown = JSON.parse(ran.stdout.trim());
		if (Array.isArray(parsed) && parsed.every((m) => typeof m === "string")) return parsed;
	} catch {
		// unknown key, unparsable output or no answer in time: fall back to omp's default
	}
	return ["interactive"];
}
